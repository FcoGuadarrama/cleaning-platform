#!/usr/bin/env bash
# Regenerates infra/nginx/snippets/cloudflare-realip.conf from Cloudflare's published ranges.
# Review the diff before committing; ranges change rarely.
set -euo pipefail
out="$(git rev-parse --show-toplevel)/infra/nginx/snippets/cloudflare-realip.conf"
{
  echo "# Generated by scripts/cloudflare-realip.sh from https://www.cloudflare.com/ips/ on $(date -u +%F)"
  for v in v4 v6; do curl -fsS "https://www.cloudflare.com/ips-$v" | sed 's/^/set_real_ip_from /; s/$/;/'; echo; done
  echo "real_ip_header CF-Connecting-IP;"
} | sed '/^$/d' > "$out.tmp"
mv "$out.tmp" "$out"
echo "wrote $out"
